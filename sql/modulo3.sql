alter table public.solicitudes add column if not exists motivo_rechazo text;

create table if not exists public.notificaciones (
    id_notificacion bigint generated by default as identity primary key,
    id_usuario bigint not null references public.usuarios(id_usuario),
    id_solicitud bigint references public.solicitudes(id_solicitud),
    tipo varchar not null,
    mensaje text not null,
    leida boolean not null default false,
    fecha_creacion timestamp not null default now()
);

create table if not exists public.citas (
    id_cita bigint generated by default as identity primary key,
    id_solicitud bigint not null references public.solicitudes(id_solicitud),
    fecha_cita date not null,
    hora_cita time not null,
    lugar varchar not null,
    fecha_registro timestamp not null default now()
);

create table if not exists public.mensajes (
    id_mensaje bigint generated by default as identity primary key,
    id_solicitud bigint not null references public.solicitudes(id_solicitud),
    id_remitente bigint not null references public.usuarios(id_usuario),
    contenido text not null,
    leido boolean not null default false,
    fecha_envio timestamp not null default now()
);

alter table public.notificaciones enable row level security;
alter table public.citas enable row level security;
alter table public.mensajes enable row level security;

revoke all on public.solicitudes, public.sesiones_abiertas, public.notificaciones, public.citas, public.mensajes
    from public, anon, authenticated;
grant select, insert, update, delete on public.solicitudes, public.sesiones_abiertas,
    public.notificaciones, public.citas, public.mensajes to service_role;
grant usage on sequence public.notificaciones_id_notificacion_seq, public.citas_id_cita_seq,
    public.mensajes_id_mensaje_seq to service_role;

create or replace function public.maow_enviar(actor bigint, mascota bigint, respuestas jsonb)
returns void language plpgsql set search_path = public, pg_temp as $$
declare
    animal mascotas%rowtype;
    solicitud bigint;
begin
    select * into animal from mascotas where id_mascota = mascota for update;
    if not found or animal.estado_adopcion is distinct from 'Disponible' then
        raise exception 'La mascota ya no está disponible.';
    end if;
    if exists (select 1 from solicitudes where id_mascota = mascota and id_adoptante = actor
               and estado_solicitud in ('Pendiente','Aprobada')) then
        raise exception 'Ya tienes una solicitud activa para esta mascota.';
    end if;
    if (respuestas->>'familia_de_acuerdo')::boolean is not true
       or (respuestas->>'compromiso_gastos')::boolean is not true
       or coalesce(respuestas->>'tipo_vivienda','') not in ('Casa propia','Departamento','Renta')
       or jsonb_typeof(respuestas->'tiene_patio') is distinct from 'boolean' then
        raise exception 'Completa el cuestionario de aptitud.';
    end if;
    insert into solicitudes (id_adoptante,id_mascota,tipo_vivienda,tiene_patio,familia_de_acuerdo,
                             compromiso_gastos,motivo_adopcion,estado_solicitud,fecha_solicitud)
    values (actor,mascota,respuestas->>'tipo_vivienda',(respuestas->>'tiene_patio')::boolean,true,true,
            respuestas->>'motivo_adopcion','Pendiente',now())
    returning id_solicitud into solicitud;
    insert into notificaciones (id_usuario,id_solicitud,tipo,mensaje)
    values (animal.id_publicador,solicitud,'solicitud_recibida','Recibiste una solicitud para ' || animal.nombre || '.');
end $$;

create or replace function public.maow_cambiar(actor bigint, solicitud bigint, nuevo text, motivo text)
returns void language plpgsql set search_path = public, pg_temp as $$
declare
    animal mascotas%rowtype;
    ficha solicitudes%rowtype;
    destino bigint;
    tipo_aviso text;
begin
    select m.* into animal from mascotas m join solicitudes s using (id_mascota)
    where s.id_solicitud = solicitud for update of m;
    select * into ficha from solicitudes where id_solicitud = solicitud for update;
    if not found or animal.estado_adopcion = 'Adoptada' then
        raise exception 'Solicitud inexistente o adopción cerrada.';
    end if;
    if nuevo = 'Cancelada' and actor = ficha.id_adoptante
       and ficha.estado_solicitud in ('Pendiente','Aprobada') then
        destino := animal.id_publicador;
        tipo_aviso := 'solicitud_cancelada';
    elsif nuevo in ('Aprobada','Rechazada') and actor = animal.id_publicador
          and ficha.estado_solicitud = 'Pendiente' then
        if nuevo = 'Rechazada' and nullif(trim(motivo),'') is null then
            raise exception 'Escribe el motivo del rechazo.';
        end if;
        destino := ficha.id_adoptante;
        tipo_aviso := case nuevo when 'Aprobada' then 'solicitud_aprobada' else 'solicitud_rechazada' end;
    else
        raise exception 'La solicitud ya cambió de estado o no tienes permiso.';
    end if;
    update solicitudes set estado_solicitud = nuevo,
        motivo_rechazo = case when nuevo = 'Rechazada' then trim(motivo) end
    where id_solicitud = solicitud;
    if nuevo = 'Cancelada' and animal.estado_adopcion = 'En Proceso'
       and not exists (select 1 from solicitudes where id_mascota = animal.id_mascota
                       and estado_solicitud in ('Pendiente','Aprobada')) then
        update mascotas set estado_adopcion = 'Disponible' where id_mascota = animal.id_mascota;
    end if;
    insert into notificaciones (id_usuario,id_solicitud,tipo,mensaje)
    values (destino,solicitud,tipo_aviso,'Solicitud para ' || animal.nombre || ' — ' || nuevo || '.');
end $$;

create or replace function public.maow_cita(actor bigint, solicitud bigint, fecha date, hora time, sitio text)
returns void language plpgsql set search_path = public, pg_temp as $$
declare
    adoptante bigint;
    nombre_animal text;
begin
    select s.id_adoptante, m.nombre into adoptante, nombre_animal
    from mascotas m join solicitudes s using (id_mascota)
    where s.id_solicitud = solicitud and m.id_publicador = actor and s.estado_solicitud = 'Aprobada'
      and m.estado_adopcion <> 'Adoptada' for update of m,s;
    if not found then raise exception 'La cita requiere una solicitud aprobada de tu publicación.'; end if;
    if fecha + hora <= (now() at time zone 'America/Mexico_City') or nullif(trim(sitio),'') is null then
        raise exception 'Indica un lugar y una fecha y hora futuras.';
    end if;
    if exists (select 1 from citas where id_solicitud = solicitud and fecha_cita = fecha and hora_cita = hora) then
        raise exception 'Ya existe una cita para esa fecha y hora.';
    end if;
    insert into citas (id_solicitud,fecha_cita,hora_cita,lugar) values (solicitud,fecha,hora,trim(sitio));
    insert into notificaciones (id_usuario,id_solicitud,tipo,mensaje) values
    (adoptante,solicitud,'cita_programada','Cita para conocer a ' || nombre_animal || ' el ' ||
     to_char(fecha,'DD/MM/YYYY') || ' a las ' || to_char(hora,'HH24:MI') || ' en ' || trim(sitio) || '.');
end $$;

create or replace function public.maow_chat(actor bigint, solicitud bigint, texto text)
returns jsonb language plpgsql set search_path = public, pg_temp as $$
begin
    perform 1 from mascotas m join solicitudes s using (id_mascota)
    where s.id_solicitud = solicitud and actor in (m.id_publicador,s.id_adoptante)
      and s.estado_solicitud in ('Pendiente','Aprobada') and m.estado_adopcion <> 'Adoptada'
    for update of m,s;
    if not found then raise exception 'La conversación está cerrada o no tienes acceso.'; end if;
    if texto is not null then
        if length(trim(texto)) not between 1 and 4000 then raise exception 'Mensaje vacío o demasiado largo.'; end if;
        insert into mensajes (id_solicitud,id_remitente,contenido) values (solicitud,actor,trim(texto));
        return '[]'::jsonb;
    end if;
    update mensajes set leido = true where id_solicitud = solicitud and id_remitente <> actor and not leido;
    return (select coalesce(jsonb_agg(jsonb_build_object('propio',id_remitente = actor,'contenido',contenido,
        'fecha_envio',fecha_envio,'leido',leido) order by fecha_envio,id_mensaje),'[]'::jsonb)
        from mensajes where id_solicitud = solicitud);
end $$;

revoke all on function public.maow_enviar(bigint,bigint,jsonb), public.maow_cambiar(bigint,bigint,text,text),
    public.maow_cita(bigint,bigint,date,time,text), public.maow_chat(bigint,bigint,text) from public, anon, authenticated;
grant execute on function public.maow_enviar(bigint,bigint,jsonb), public.maow_cambiar(bigint,bigint,text,text),
    public.maow_cita(bigint,bigint,date,time,text), public.maow_chat(bigint,bigint,text) to service_role;
commit;
